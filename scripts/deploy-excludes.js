#!/usr/bin/env node
/**
 * Print the rsync exclude patterns the production deploy must use.
 *
 * WHY THIS EXISTS
 *
 * `deploy.yml` ships the build with `rsync -az --delete`. Since the publication
 * allowlist landed (scripts/lib/published-books.js), a build no longer CONTAINS
 * the held-back books — so `--delete` would remove their pages from the server.
 * That would turn a freeze into a deletion of live pages as a side effect of a
 * rule that only meant "stop publishing new ones", and it would do it silently.
 *
 * ⚠️ It would also not be a clean 404. `svelte.config.js` sets
 * `fallback: '200.html'` and nginx does `try_files $uri $uri/ /200.html`, so a
 * removed page answers **HTTP 200 with the SPA shell** — an indexed soft-404,
 * which crawlers sit on rather than deindex. Retiring those URLs for real is a
 * separate decision needing server-side work; this script is the freeze.
 *
 * HOW IT WORKS
 *
 * rsync's `--delete` PROTECTS anything matching an `--exclude` on the receiving
 * side: the pattern means "ignore this path", not "remove it". The deploy
 * already relies on that for `downloads/` (PDFs are built separately and live
 * only on the server). This extends the same mechanic, deliberately, to every
 * book the allowlist holds back.
 *
 * ⚠️ Never add `--delete-excluded` to the deploy. It inverts this, and would
 * delete precisely what the list is here to preserve.
 *
 * The patterns are UNANCHORED (`slug/`, not `/slug/`) so they match that
 * directory at any depth. One pattern per book therefore covers every surface a
 * book occupies in the build — `build/<slug>/` (reader pages),
 * `build/print/<slug>/` (PDF source routes) and `build/content/<slug>/` (the
 * synced JSON and HTML) — and keeps covering it if a new per-book route is added
 * later. An anchored list would silently miss that new route.
 *
 * The freeze list is DERIVED, never restated: it is the complement of the
 * allowlist over the books that actually exist in the efni source tree, so a
 * book cannot be both unsynced and unprotected.
 *
 * Usage:
 *   node scripts/deploy-excludes.js [--source ../namsbokasafn-efni]
 *
 * Writes one pattern per line on stdout, for `rsync --exclude-from=-` or a file.
 */

import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import { getSourceBooks } from './sync-content.js';
import { withheldBooks } from './lib/published-books.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, '..');
const DEFAULT_SOURCE = resolve(projectRoot, '..', 'namsbokasafn-efni');

/**
 * Patterns to protect on the server, given the books present in `sourceDir`.
 *
 * `downloads/` is always first: the PDFs are generated by a separate command
 * (`npm run build:full`) and exist only on the server, so a plain `--delete`
 * would wipe them. That exclusion predates the freeze and is unrelated to it.
 */
export function deployExcludes(availableBooks) {
	return ['downloads/', ...withheldBooks(availableBooks).map((slug) => `${slug}/`)];
}

function parseArgs(args) {
	const options = { source: DEFAULT_SOURCE };
	for (let i = 0; i < args.length; i++) {
		if (args[i] === '--source' || args[i] === '-s') {
			options.source = resolve(args[++i] || DEFAULT_SOURCE);
		}
	}
	return options;
}

function main() {
	const options = parseArgs(process.argv.slice(2));
	const availableBooks = getSourceBooks(options.source);

	// A source tree that yields no books means the checkout is missing or
	// malformed. Emitting just `downloads/` would look like a valid answer while
	// protecting nothing — so fail loudly instead of shipping a silent deletion.
	if (availableBooks.length === 0) {
		console.error(`Error: no books found in ${options.source}`);
		console.error('Refusing to emit an exclude list that protects nothing.');
		process.exit(1);
	}

	for (const pattern of deployExcludes(availableBooks)) {
		console.log(pattern);
	}
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
	main();
}
